function pageText(result, i) {
  return (result.pages[i]?.text || "")
    .replace(/-- \d+ of 51 --/g, "")
    .replace(/\u0000/g, "")
    .trim();
}

function softJoin(lines) {
  const paras = [];
  let buf = "";
  for (const l of lines) {
    if (!buf) {
      buf = l;
      continue;
    }
    if (/[-–]$/.test(buf)) {
      buf = buf.replace(/[-–]$/, "") + l;
    } else if (
      /^(Article|Chapter|Appendix|Preamble|Name|Explanation|Fundamental|Objectives|Means|Membership|Organizational|Central|Branch|Women|Duties|Qualifications|Procedure|Oath|Baitul|Removal|Interpretation|Amendment|A\.|B\.|Whereas|Therefore|Permanent|Da'wah|Da’wah|Eligibility|Supporter|Information|Sub-Branch)/i.test(
        l,
      )
    ) {
      paras.push(buf);
      buf = l;
    } else {
      buf += " " + l;
    }
  }
  if (buf) paras.push(buf);
  return paras;
}

function cleanEn(text) {
  return text
    .replace(/\r/g, "")
    .replace(/[\u0080-\u009F]+/g, "")
    .replace(/ملسو هيلع هللا ىلص/g, "ﷺ")
    .replace(/\s+([.,;:!?])/g, "$1")
    .replace(/ {2,}/g, " ");
}

function splitSections(joinedText) {
  const sectionDefs = [
    {
      id: "preamble",
      titleEn: "Preamble",
      titleBn: "ভূমিকা",
      titleKo: "전문",
      pattern: /^Preamble\b/i,
    },
    {
      id: "chapter-1",
      titleEn: "Chapter One",
      titleBn: "প্রথম অধ্যায়",
      titleKo: "제1장",
      pattern: /^Chapter One\b/i,
    },
    {
      id: "chapter-2",
      titleEn: "Chapter Two",
      titleBn: "দ্বিতীয় অধ্যায়",
      titleKo: "제2장",
      pattern: /^Chapter Two\b/i,
    },
    {
      id: "chapter-3",
      titleEn: "Chapter Three",
      titleBn: "তৃতীয় অধ্যায়",
      titleKo: "제3장",
      pattern: /^Chapter Three\b/i,
    },
    {
      id: "chapter-4",
      titleEn: "Chapter Four–Seven",
      titleBn: "চতুর্থ–সপ্তম অধ্যায়",
      titleKo: "제4–7장",
      pattern: /^Chapter Four\b/i,
    },
    {
      id: "appendices",
      titleEn: "Appendices",
      titleBn: "পরিশিষ্ট",
      titleKo: "부록",
      pattern: /^Appendix/i,
    },
  ];
  const parts = [];
  const rx =
    /(^|\n)(Preamble|Chapter One|Chapter Two|Chapter Three|Chapter Four|Appendix-\d+|Appendix\s+\d+|Appendix(?!-))/gi;
  const indices = [];
  let m;
  const text = "\n" + joinedText;
  while ((m = rx.exec(text)) !== null) {
    indices.push({ index: m.index + m[1].length, label: m[2] });
  }
  for (let i = 0; i < indices.length; i++) {
    const start = indices[i].index;
    const end = i + 1 < indices.length ? indices[i + 1].index : text.length;
    const chunk = text.slice(start, end).trim();
    const label = indices[i].label;
    let sec = sectionDefs.find((s) => s.pattern.test(label));
    if (/^Appendix/i.test(label)) {
      sec = sectionDefs.find((s) => s.id === "appendices");
    }
    if (!sec) continue;
    const existing = parts.find((p) => p.id === sec.id);
    if (existing) existing.bodyEn += "\n\n" + chunk;
    else
      parts.push({
        id: sec.id,
        titleEn: sec.titleEn,
        titleBn: sec.titleBn,
        titleKo: sec.titleKo,
        bodyEn: chunk,
      });
  }
  return parts;
}

function toBlocks(body) {
  let chunks = body
    .split(/\n\n+/)
    .map((p) => p.replace(/\n/g, " ").replace(/\s+/g, " ").trim())
    .filter(Boolean);
  if (chunks.length <= 2 && body.length > 1200) {
    const t = chunks.join("\n\n");
    const parts = t.split(
      /(?=(?:Article\s+\d+|Chapter\s+(?:One|Two|Three|Four|Five|Six|Seven|\d+)|Appendix-?\d*|ধারা-?\d+|প্রথম অধ্যায়|দ্বিতীয়|তৃতীয়|চতুর্থ|ভূমিকা|ব্যাখ্যা|উদ্দেশ্য|স্থায়ী|দাওয়াহ|মৌলিক|Eligibility|Membership Procedure|Duties|Central Organization|Branch Organization|Women|Baitul|Election|Removal|Interpretation|Amendment|Oath of|Information on|제\s*\d+\s*조|부록))/i,
    );
    chunks = parts.map((p) => p.trim()).filter(Boolean);
  }
  return chunks;
}

function splitKo(ko) {
  // PDF Korean omits full Ch.1; membership follows preamble, then Art.12 structure
  const preambleEnd = ko.search(/제정한다\.?/);
  let preamble = "";
  let rest = ko;
  if (preambleEnd >= 0) {
    preamble = ko.slice(0, preambleEnd + "제정한다.".length).trim();
    rest = ko.slice(preambleEnd + "제정한다.".length).trim();
  } else {
    const idx = ko.indexOf("전문");
    preamble = idx >= 0 ? ko.slice(idx).trim() : "";
    rest = "";
  }

  const map = { preamble };

  const ch3Idx = rest.search(/제\s*12\s*조|본 조직의 조직 체계|제\s*3\s*장/);
  const ch4Idx = rest.search(/제\s*26\s*조|중앙 여성|여성부|제\s*4\s*장|제\s*28\s*조/);
  const appIdx = rest.search(/부록/);

  const ends = [ch3Idx, ch4Idx, appIdx, rest.length]
    .filter((n) => n >= 0)
    .sort((a, b) => a - b);

  // Membership block = chapter-2 (Ch.1 largely missing in KO PDF)
  const membershipEnd =
    ends.find((n) => n === ch3Idx || n === ch4Idx || n === appIdx) ?? rest.length;
  if (rest && membershipEnd > 0) {
    const memberText = rest.slice(0, membershipEnd).trim();
    if (memberText) map["chapter-2"] = memberText;
  }

  if (ch3Idx >= 0) {
    const end =
      [ch4Idx, appIdx, rest.length].filter((n) => n > ch3Idx).sort((a, b) => a - b)[0] ??
      rest.length;
    map["chapter-3"] = rest.slice(ch3Idx, end).trim();
  }
  if (ch4Idx >= 0) {
    const end =
      [appIdx, rest.length].filter((n) => n > ch4Idx).sort((a, b) => a - b)[0] ??
      rest.length;
    map["chapter-4"] = rest.slice(ch4Idx, end).trim();
  }
  if (appIdx >= 0) {
    map["appendices"] = rest.slice(appIdx).trim();
  }

  return map;
}

/** Each non-empty line becomes its own content block (preserves BN/KO headings). */
function linesToBlocks(body) {
  return body
    .replace(/\r/g, "")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
}

